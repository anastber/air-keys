"""Summarize evaluation runs into ml/experiments/README.md.

Reads every ml/experiments/<date>-<protocol>-<model>/metrics.json (keeping
the latest run per protocol and model) and writes one table per protocol,
plus two views derived from the stored confusion matrices:
  - 4-class view: every class but ok_sign / rock_on / call_me merged into
    no_gesture — the task the deployed MLP is scored on, so the candidates
    can be compared with it like for like;
  - 8 gestures only: accuracy on the samples whose true class isn't
    no_gesture.

Usage (from repo root): uv run python -m ml.summarize
"""

import json
from pathlib import Path

import numpy as np

from ml.models import BACKGROUND_LABEL

EXPERIMENTS_DIR = Path(__file__).resolve().parent / "experiments"
DEPLOYED_CLASSES = {"ok_sign", "rock_on", "call_me"}
PROTOCOL_TITLES = {
    "cv": "Model selection — grouped 5-fold CV on HaGRID training subjects",
    "p1": "P1 — HaGRID test subjects (people never seen in training)",
    "p2": "P2 — deployed MLP on HaGRID test subjects",
    "p3": "P3 — own_v2, live webcam (2 sessions)",
}


def latest_runs() -> dict[tuple[str, str], dict]:
    runs: dict[tuple[str, str], dict] = {}
    for path in sorted(EXPERIMENTS_DIR.glob("*/metrics.json")):
        result = json.loads(path.read_text())
        result["dir"] = path.parent.name
        runs[(result["protocol"], result["model"])] = result  # sorted: latest wins
    return runs


def derived_accuracies(metrics: dict) -> tuple[float, float | None]:
    """(4-class-view accuracy, 8-gesture accuracy) from a confusion matrix."""
    labels = metrics["labels"]
    cm = np.array(metrics["confusion_matrix"])  # last column: "other"

    def view(label: str) -> str:
        return label if label in DEPLOYED_CLASSES else BACKGROUND_LABEL

    predicted = [view(label) for label in labels] + [BACKGROUND_LABEL]
    correct = sum(
        cm[i, j]
        for i, true in enumerate(labels)
        for j in range(cm.shape[1])
        if view(true) == predicted[j]
    )
    gestures = [i for i, label in enumerate(labels) if label != BACKGROUND_LABEL]
    eight = None
    if len(labels) == 9:
        eight = float(sum(cm[i, i] for i in gestures) / cm[gestures].sum())
    return float(correct / cm.sum()), eight


def fmt_ci(value: float, ci: list[float]) -> str:
    return f"{value:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]"


def main() -> None:
    runs = latest_runs()
    lines = [
        "# Experiment results",
        "",
        "Generated by `uv run python -m ml.summarize` from the `metrics.json` of each "
        "run below — do not edit by hand. Each run's folder has its full report, "
        "confusion matrix, dataset hashes and the command that reproduces it. "
        "Values in brackets are bootstrap 95 % confidence intervals (resampling "
        "subjects for HaGRID, recording bursts for own data).",
        "",
    ]
    for protocol, title in PROTOCOL_TITLES.items():
        rows = sorted(
            (r for (p, _), r in runs.items() if p == protocol), key=lambda r: r["model"]
        )
        if not rows:
            continue
        lines += [f"## {title}", ""]
        if protocol == "cv":
            lines += ["| Model | Accuracy | Macro-F1 | Run |", "|---|---|---|---|"]
            for r in rows:
                s = r["cv"]["summary"]
                lines.append(
                    f"| `{r['model']}` | {s['accuracy']['mean']:.3f} ± "
                    f"{s['accuracy']['std']:.3f} | {s['macro_f1']['mean']:.3f} ± "
                    f"{s['macro_f1']['std']:.3f} | [{r['dir']}]({r['dir']}/report.md) |"
                )
        else:
            lines += [
                "| Model | Accuracy | Macro-F1 | 4-class view | 8 gestures only | Run |",
                "|---|---|---|---:|---:|---|",
            ]
            for r in rows:
                m = r["metrics"]
                four, eight = derived_accuracies(m)
                lines.append(
                    f"| `{r['model']}` | {fmt_ci(m['accuracy'], m['ci95']['accuracy'])} "
                    f"| {fmt_ci(m['macro_f1'], m['ci95']['macro_f1'])} | {four:.3f} | "
                    f"{'—' if eight is None else f'{eight:.3f}'} | "
                    f"[{r['dir']}]({r['dir']}/report.md) |"
                )
        lines.append("")
        if protocol == "p3" and all("by_session" in r["metrics"] for r in rows):
            lines += [
                "**P3 by recording session** — whether results hold under other "
                "lighting:",
                "",
                "| Model | Session | Lighting | Gestures only | `no_gesture` recall |",
                "|---|---|---|---:|---:|",
            ]
            for r in rows:
                for session, x in r["metrics"]["by_session"].items():
                    lines.append(
                        f"| `{r['model']}` | `{session}` | {', '.join(x['lighting'])} "
                        f"| {x['gesture_accuracy']:.3f} | {x['no_gesture_recall']:.3f} |"
                    )
            lines.append("")
    lines += [
        "**4-class view:** every class except `ok_sign`, `rock_on` and `call_me` "
        "counted as `no_gesture` — the task the deployed MLP solves, for a like-for-"
        "like comparison. **8 gestures only:** accuracy on samples whose true class "
        "is a gesture (excludes `no_gesture`). Both are derived from the stored "
        "confusion matrices, without confidence intervals.",
        "",
    ]
    (EXPERIMENTS_DIR / "README.md").write_text("\n".join(lines))
    print(f"Wrote {EXPERIMENTS_DIR / 'README.md'}")


if __name__ == "__main__":
    main()
